
fruits=["Apple","Banana","Cherry","Date","Elderberry","Grapes"]

print("Fruits List=",fruits)       # Output: ["Apple","Banana","Cherry","Date","Elderberry","Grapes"]


# Calling List Elements by Positive Index Numbers
print("")

print("Calling List Elements by Positive Index Numbers:")
print(fruits[0])    # Output: Apple
print(fruits[3])    # Output: Date
print(fruits[5])    # Output: Grapes

# Calling List Elements by Negative Index Numbers
print("")

print("Calling List Elements by Negative Index Numbers:")
print(fruits[-6])   # Output: Apple
print(fruits[-3])   # Output: Date
print(fruits[-1])